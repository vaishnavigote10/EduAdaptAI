"""Study-material generators: topic PPT deck (python-pptx) and handwritten-style notes (HTML)."""
import html, io, re
from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.util import Inches, Pt
from . import rag, llm

INK, PAPER, AMBER, MINT = RGBColor(0x0E, 0x1B, 0x17), RGBColor(0xEC, 0xEF, 0xE6), RGBColor(0xF2, 0xB8, 0x4B), RGBColor(0x7F, 0xE0, 0xB0)


def key_points(topic, n=7):
    out = []
    for c in topic.chunks.select_related("document"):
        s = [x for x in re.split(r"(?<=[.!?])\s+", c.text) if 6 <= len(x.split()) <= 30]
        if s: out.append((s[0], f"{c.document.title} · {c.location}"))
        if len(s) > 1 and len(out) < n: out.append((s[1], f"{c.document.title} · {c.location}"))
    return out[:n]


def _bg(slide, rgb):
    f = slide.background.fill; f.solid(); f.fore_color.rgb = rgb


def _text(slide, x, y, w, h, text, size, color, bold=False):
    tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h)); tf = tb.text_frame; tf.word_wrap = True
    p = tf.paragraphs[0]; p.text = text; p.font.size = Pt(size); p.font.bold = bold; p.font.color.rgb = color
    return tf


def build_ppt(topic):
    prs = Presentation(); prs.slide_width, prs.slide_height = Inches(13.333), Inches(7.5)
    blank = prs.slide_layouts[6]
    s = prs.slides.add_slide(blank); _bg(s, INK)
    _text(s, 0.9, 2.4, 11.5, 1.6, topic.name, 54, PAPER, True)
    _text(s, 0.9, 4.2, 11.5, 0.8, f"Generated by EduAdapt AI from your course material · {topic.course.name}", 18, MINT)
    pts = key_points(topic)
    for i in range(0, len(pts), 3):
        s = prs.slides.add_slide(blank); _bg(s, INK)
        _text(s, 0.9, 0.6, 11.5, 0.9, f"{topic.name}", 30, AMBER, True)
        y = 1.8
        for text, src in pts[i:i + 3]:
            _text(s, 0.9, y, 11.5, 1.2, text, 22, PAPER); _text(s, 0.9, y + 1.0, 11.5, 0.4, "Source: " + src, 12, MINT); y += 1.75
    s = prs.slides.add_slide(blank); _bg(s, INK)
    _text(s, 0.9, 0.6, 11.5, 0.9, "Check yourself", 30, AMBER, True)
    y = 1.8
    for q in topic.questions.all()[:3]:
        _text(s, 0.9, y, 11.5, 1.2, q.prompt, 20, PAPER); y += 1.6
    buf = io.BytesIO(); prs.save(buf); buf.seek(0); return buf


def notes_html(topic):
    pts = key_points(topic, 9)
    summary = llm.chat("Write 3 short, friendly study-note sentences.", " ".join(p for p, _ in pts)) if llm.available() else None
    rows = "".join(f"<li>{html.escape(t)}<small> — {html.escape(src)}</small></li>" for t, src in pts)
    qs = "".join(f"<li>{html.escape(q.prompt)}</li>" for q in topic.questions.all()[:4])
    pre = ", ".join(html.escape(p.name) for p in topic.prerequisites.all()) or "none"
    return f"""<!doctype html><meta charset="utf-8"><title>{html.escape(topic.name)} notes</title>
<link href="https://fonts.googleapis.com/css2?family=Caveat:wght@500;700&display=swap" rel="stylesheet">
<style>body{{margin:0;background:#d9d4c7;display:grid;place-items:center;padding:40px 16px;font-family:'Caveat',cursive}}
.page{{width:min(760px,100%);padding:56px 48px 56px 90px;color:#1b2a6b;font-size:25px;line-height:36px;border-radius:4px;
background:linear-gradient(90deg,transparent 70px,#e07a7a 70px,#e07a7a 72px,transparent 72px),repeating-linear-gradient(#fbfaf5 0 35px,#9ec4e8 35px 36px);
box-shadow:0 30px 60px rgba(0,0,0,.28),0 2px 0 #fff inset;transform:rotate(-.4deg)}}
h1{{font-size:46px;line-height:50px;margin:0 0 18px;color:#0b1a55;text-decoration:underline wavy #f2b84b}}
h2{{font-size:30px;margin:22px 0 4px;color:#9b2c2c}}ul{{margin:0;padding-left:26px}}li{{margin-bottom:6px}}small{{color:#5a6aa8;font-size:18px}}
.hl{{background:linear-gradient(transparent 55%,#ffe27a 55%)}}@media print{{body{{background:#fff}}.page{{box-shadow:none;transform:none}}}}</style>
<div class="page"><h1>{html.escape(topic.name)}</h1><p><span class="hl">Before this, know:</span> {pre}</p>
{f'<p>{html.escape(summary)}</p>' if summary else ''}<h2>Key ideas</h2><ul>{rows}</ul>
<h2>Test yourself</h2><ul>{qs}</ul></div>"""
